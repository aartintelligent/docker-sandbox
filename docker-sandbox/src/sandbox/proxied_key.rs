//! API keys a sandbox uses without holding them: a placeholder in the
//! sandbox, the key written in its place by the proxy.
//!
//! The credential a kit declares for its agent, such as `anthropic` for the
//! `claude` kit, is injected with the value the daemon holds for its service,
//! a subscription for instance, when the daemon authorizes it
//! ([`CreateRequest::with_bindings_path`]); when it withholds it, a value
//! pushed for that service is not injected either
//! ([`CredentialsOutcome::withheld`]). A [`ProxiedKey`] gives
//! the agent a key of the program's own instead, without depending on
//! authorization: the sandbox is created with a placeholder in the variable
//! the agent reads its key from ([`CreateRequest::with_proxied_key`]), and a
//! custom secret tells the proxy to write the key in place of the placeholder
//! in the requests to the hosts of the key ([`Sandbox::push_proxied_keys`]).
//! The key itself only travels over the socket, to the daemon.
//!
//! The hosts are given explicitly: the key reaches no other one, whatever the
//! network rules of the sandbox allow. The agent has to send the content of
//! the variable in a header of its requests, as an API client does with a key.

use std::collections::hash_map::RandomState;
use std::fmt::Write as _;
use std::hash::{BuildHasher, Hasher};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use super::{CreateRequest, CredentialsOutcome, CredentialsUpdate, CustomSecret, Sandbox, Secret};
use crate::error::{Error, Result};

/// Prefix of the placeholders this crate generates, the one of the custom
/// secrets of the CLI.
const PLACEHOLDER_PREFIX: &str = "sbx-cs-";

/// Keys generated by this process, so that two placeholders made at the same
/// instant differ.
static GENERATED: AtomicU64 = AtomicU64::new(0);

/// An API key given to a sandbox through the proxy alone: the sandbox holds a
/// placeholder in the variable `env`, and the proxy writes the key in its
/// place in the requests to `hosts`.
///
/// ```no_run
/// use docker_sandbox::Client;
/// use docker_sandbox::kit::KitPackage;
/// use docker_sandbox::sandbox::ProxiedKey;
///
/// # async fn run(key_from_the_host: String) -> docker_sandbox::Result<()> {
/// let client = Client::connect().await?;
/// let package = KitPackage::open("/var/lib/kits/claude")?;
/// let key = ProxiedKey::new("ANTHROPIC_API_KEY", ["api.anthropic.com"], key_from_the_host)?;
/// // The placeholder goes into the sandbox, at its creation…
/// let request = package.request("job-42")?.with_proxied_key(&key);
/// package.create_with(&client, &request).await?;
/// // …and the key to the proxy, through the socket.
/// client.sandbox("job-42").push_proxied_keys(&[key]).await?;
/// # Ok(())
/// # }
/// ```
#[derive(Debug, Clone)]
pub struct ProxiedKey {
    /// Variable of the sandbox holding the placeholder.
    env: String,
    /// Hosts the key is written for.
    hosts: Vec<String>,
    /// What the sandbox holds in place of the key.
    placeholder: String,
    /// The key.
    value: Secret,
}

impl ProxiedKey {
    /// The key `value`, read by the agent from the variable `env` and sent to
    /// `hosts`, e.g. `api.anthropic.com`. Its placeholder is generated:
    /// unique, it is no secret, since the sandbox sees it.
    ///
    /// # Errors
    ///
    /// Returns [`Error::InvalidRequest`] when `env` is not the name of a
    /// variable, or when `hosts` is empty or holds an empty host.
    pub fn new(
        env: impl Into<String>,
        hosts: impl IntoIterator<Item = impl Into<String>>,
        value: impl Into<Secret>,
    ) -> Result<Self> {
        Self::checked(
            env.into(),
            hosts.into_iter().map(Into::into).collect(),
            value.into(),
        )
    }

    /// [`ProxiedKey::new`], compiled once whatever the types of its
    /// arguments.
    fn checked(env: String, hosts: Vec<String>, value: Secret) -> Result<Self> {
        if !is_variable_name(&env) {
            return Err(Error::InvalidRequest(format!(
                "{env:?} is not the name of an environment variable"
            )));
        }
        if hosts.is_empty() || hosts.iter().any(|host| host.trim().is_empty()) {
            return Err(Error::InvalidRequest(format!(
                "the key of {env} names no host: it would be written for none"
            )));
        }
        Ok(Self {
            env,
            hosts,
            placeholder: placeholder(),
            value,
        })
    }

    /// Variable of the sandbox holding the placeholder.
    #[must_use]
    pub fn env(&self) -> &str {
        &self.env
    }

    /// Hosts the key is written for.
    #[must_use]
    pub fn hosts(&self) -> &[String] {
        &self.hosts
    }

    /// What the sandbox holds in place of the key.
    #[must_use]
    pub fn placeholder(&self) -> &str {
        &self.placeholder
    }

    /// The custom secret that tells the proxy where to write the key.
    fn custom_secret(&self) -> CustomSecret {
        CustomSecret::new(self.hosts.clone(), &self.placeholder, self.value.clone())
            .with_env_name(&self.env)
    }
}

impl CreateRequest {
    /// Sets the placeholder of `key` in the variable it names, for the
    /// sandbox and every command run in it. The key itself goes with
    /// [`Sandbox::push_proxied_keys`], once the sandbox exists.
    #[must_use]
    pub fn with_proxied_key(self, key: &ProxiedKey) -> Self {
        self.with_env(key.env.clone(), key.placeholder.clone())
    }
}

impl CredentialsUpdate {
    /// Adds the custom secret of `key`. Custom secrets replace those of the
    /// sandbox as a whole: one update carries every key of the sandbox.
    #[must_use]
    pub fn with_proxied_key(self, key: &ProxiedKey) -> Self {
        self.with_custom_secret(key.custom_secret())
    }
}

impl Sandbox {
    /// Gives the sandbox `keys`, created with their placeholders
    /// ([`CreateRequest::with_proxied_key`]): the proxy writes each key in
    /// place of its placeholder in the requests to its hosts. The keys
    /// replace the custom secrets the sandbox had.
    ///
    /// # Errors
    ///
    /// Fails as [`Sandbox::push_credentials`] does.
    pub async fn push_proxied_keys(&self, keys: &[ProxiedKey]) -> Result<CredentialsOutcome> {
        let update = keys.iter().fold(
            CredentialsUpdate::default(),
            CredentialsUpdate::with_proxied_key,
        );
        self.push_credentials(&update).await
    }
}

/// A placeholder no other key uses: [`PLACEHOLDER_PREFIX`] and 32 hexadecimal
/// digits, from the random keys of the standard hasher, the time and a count
/// of the keys of this process.
fn placeholder() -> String {
    let count = GENERATED.fetch_add(1, Ordering::Relaxed);
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let mut placeholder = String::from(PLACEHOLDER_PREFIX);
    for part in 0..2_u64 {
        let mut hasher = RandomState::new().build_hasher();
        hasher.write_u128(now);
        hasher.write_u64(count);
        hasher.write_u64(part);
        let _ = write!(placeholder, "{:016x}", hasher.finish());
    }
    placeholder
}

/// Whether `name` is the name of an environment variable.
fn is_variable_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A key of the tests, with a dummy value.
    fn key() -> ProxiedKey {
        ProxiedKey::new(
            "API_KEY",
            ["api.example.com", "mcp.example.com"],
            "dummy-value",
        )
        .unwrap()
    }

    #[test]
    fn keys_hold_their_variable_hosts_and_a_fresh_placeholder() {
        let key = key();
        assert_eq!(key.env(), "API_KEY");
        assert_eq!(key.hosts(), ["api.example.com", "mcp.example.com"]);
        assert!(key.placeholder().starts_with("sbx-cs-"));
        assert_eq!(key.placeholder().len(), "sbx-cs-".len() + 32);
        let other = ProxiedKey::new("API_KEY", ["api.example.com"], "dummy-value").unwrap();
        assert_ne!(key.placeholder(), other.placeholder());
        assert!(!format!("{key:?}").contains("dummy-value"), "{key:?}");
    }

    #[test]
    fn keys_for_no_host_or_no_variable_are_refused() {
        let refusal = |env: &str, hosts: &[&str]| {
            ProxiedKey::new(env, hosts.iter().copied(), "dummy")
                .unwrap_err()
                .to_string()
        };
        assert!(refusal("API_KEY", &[]).contains("names no host"));
        assert!(refusal("API_KEY", &["api.example.com", " "]).contains("names no host"));
        assert!(refusal("1KEY", &["api.example.com"]).contains("not the name"));
        assert!(refusal("", &["api.example.com"]).contains("not the name"));
        assert!(refusal("API-KEY", &["api.example.com"]).contains("not the name"));
    }

    #[test]
    fn the_custom_secret_targets_the_hosts_of_the_key() {
        let key = key();
        let secret = key.custom_secret();
        assert_eq!(secret.sentinel, key.placeholder());
        assert_eq!(secret.target, "api.example.com");
        assert_eq!(secret.targets, key.hosts());
        assert_eq!(secret.env_name.as_deref(), Some("API_KEY"));
        assert_eq!(secret.value.expose_secret(), "dummy-value");
    }
}
